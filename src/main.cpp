void setup() {

  // setup serial connection
  Serial.begin(9600);
  pinMode(movedetec, INPUT);
  pinMode(laser, INPUT);

  if (!oled.begin(SSD1306_SWITCHCAPVCC, 0x3C))
  {
    Serial.println(F("failed to start SSD1306 OLED"));
    while (1)
      ;
  }
  delay(2000);
  oled.setCursor(0,10);
}

